-- ============================================================================
-- Casa Común · esquema para Supabase
-- Base de datos para un proyecto Supabase dedicado a una sola casa.
-- Consulta docs/SUPABASE.md antes de habilitar el acceso desde Flutter.
-- ============================================================================

begin;

-- ---------------------------------------------------------------------------
-- 1. Perfiles (un perfil por usuario de Supabase Auth)
-- ---------------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  username text not null unique,
  role text not null default 'tenant' check (role in ('admin', 'tenant')),
  color_hex text not null default '#4D96FF',
  joined_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- 2. Configuración de la casa
-- ---------------------------------------------------------------------------
create table if not exists public.house_settings (
  id integer primary key default 1 check (id = 1),
  house_name text not null default 'Casa Común',
  monthly_amount integer not null default 60000,
  due_day integer not null default 29,
  reminder_days integer[] not null default '{25,26,27,28,29}',
  rotation_pairs jsonb not null default '[]'::jsonb,
  bag_order uuid[] not null default '{}',
  updated_at timestamptz not null default now()
);

insert into public.house_settings (id)
values (1)
on conflict (id) do nothing;

-- ---------------------------------------------------------------------------
-- 3. Datos de la casa
-- ---------------------------------------------------------------------------
create table if not exists public.week_overrides (
  week_start date primary key,
  team uuid[] not null check (array_length(team, 1) = 2),
  bag_buyer uuid not null references public.profiles(id) on delete cascade,
  created_by uuid references public.profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.task_completions (
  task_id text primary key,
  week_start date not null,
  zone text check (zone in ('bano', 'cocina', 'sala', 'piso')),
  kind text not null check (kind in ('cleaning', 'bags')),
  completed_by uuid not null references public.profiles(id) on delete cascade,
  completed_at timestamptz not null default now()
);

create table if not exists public.trash_state (
  id integer primary key default 1 check (id = 1),
  order_ids uuid[] not null default '{}',
  current_index integer not null default 0,
  last_emptied_at timestamptz,
  last_emptied_by uuid references public.profiles(id) on delete set null,
  updated_at timestamptz not null default now()
);

insert into public.trash_state (id)
values (1)
on conflict (id) do nothing;

create table if not exists public.trash_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  emptied_at timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- Tareas personalizadas (creadas por el administrador, asignadas a personas)
-- ---------------------------------------------------------------------------
create table if not exists public.custom_tasks (
  id text primary key,
  title text not null,
  notes text not null default '',
  icon_key text not null default 'checklist',
  color_hex text not null default '#4D96FF',
  assignee_ids uuid[] not null default '{}',
  week_start date not null,
  repeat_weekly boolean not null default false,
  created_by uuid references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.custom_turns (
  id text primary key,
  title text not null,
  notes text not null default '',
  icon_key text not null default 'cart',
  color_hex text not null default '#30D158',
  order_ids uuid[] not null default '{}',
  current_index integer not null default 0,
  last_done_at timestamptz,
  last_done_by uuid references public.profiles(id) on delete set null,
  history jsonb not null default '[]'::jsonb,
  created_by uuid references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.payments (
  month text not null check (month ~ '^\d{4}-\d{2}$'),
  user_id uuid not null references public.profiles(id) on delete cascade,
  paid boolean not null default false,
  paid_at timestamptz,
  marked_by uuid references public.profiles(id) on delete set null,
  primary key (month, user_id)
);

create table if not exists public.alert_reads (
  user_id uuid not null references public.profiles(id) on delete cascade,
  alert_id text not null,
  read_at timestamptz not null default now(),
  primary key (user_id, alert_id)
);

-- ---------------------------------------------------------------------------
-- 5. Acceso a la casa
-- ---------------------------------------------------------------------------
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

create or replace function public.is_house_member()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.profiles where id = auth.uid()
  );
$$;

-- Solo el operador del proyecto crea perfiles y concede roles.
drop trigger if exists on_auth_user_created on auth.users;
drop function if exists public.handle_new_user();

revoke execute on function public.is_admin(), public.is_house_member()
  from public, anon, authenticated;
grant execute on function public.is_admin(), public.is_house_member()
  to authenticated;

-- Si se ejecutó el esquema anterior, bloquea el acceso a los JSON heredados.
do $$
begin
  if to_regclass('public.house_state') is not null then
    execute 'revoke all on public.house_state from public, anon, authenticated';
    execute 'drop policy if exists "state read" on public.house_state';
    execute 'drop policy if exists "state write" on public.house_state';
  end if;
end;
$$;

-- ---------------------------------------------------------------------------
-- 6. Row Level Security
-- ---------------------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.house_settings enable row level security;
alter table public.week_overrides enable row level security;
alter table public.task_completions enable row level security;
alter table public.trash_state enable row level security;
alter table public.trash_logs enable row level security;
alter table public.payments enable row level security;
alter table public.alert_reads enable row level security;

-- Concesiones explícitas para la API; las políticas siguientes acotan las filas.
revoke all on public.house_settings, public.week_overrides,
  public.task_completions, public.trash_state, public.trash_logs,
  public.custom_tasks, public.custom_turns, public.payments, public.alert_reads
  from public, anon, authenticated;

grant select, insert, update, delete on public.house_settings,
  public.week_overrides, public.task_completions, public.custom_tasks,
  public.custom_turns, public.payments, public.alert_reads to authenticated;
grant select, update on public.trash_state to authenticated;
grant select, insert on public.trash_logs to authenticated;
grant usage on sequence public.trash_logs_id_seq to authenticated;

-- Tareas personalizadas: todos leen; solo el admin escribe.
drop policy if exists "custom_tasks read" on public.custom_tasks;
create policy "custom_tasks read" on public.custom_tasks
  for select to authenticated using ((select public.is_house_member()));

drop policy if exists "custom_tasks admin write" on public.custom_tasks;
create policy "custom_tasks admin write" on public.custom_tasks
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "custom_turns read" on public.custom_turns;
create policy "custom_turns read" on public.custom_turns
  for select to authenticated using ((select public.is_house_member()));

drop policy if exists "custom_turns admin write" on public.custom_turns;
create policy "custom_turns admin write" on public.custom_turns
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- Perfiles: el rol y la afiliación a la casa se gestionan fuera de la app.
revoke all on public.profiles from public, anon, authenticated;
revoke insert (id, name, username, role, color_hex, joined_at, created_at),
       update (id, name, username, role, color_hex, joined_at, created_at)
  on public.profiles from public, anon, authenticated;
grant select on public.profiles to authenticated;
grant update (name, color_hex) on public.profiles to authenticated;
drop policy if exists "profiles read" on public.profiles;
create policy "profiles read" on public.profiles
  for select to authenticated using ((select public.is_house_member()));

drop policy if exists "profiles update own" on public.profiles;
create policy "profiles update own" on public.profiles
  for update to authenticated
  using (id = auth.uid() or public.is_admin())
  with check (id = auth.uid() or public.is_admin());

-- Configuración: todos leen; solo el admin cambia.
drop policy if exists "settings read" on public.house_settings;
create policy "settings read" on public.house_settings
  for select to authenticated using ((select public.is_house_member()));

drop policy if exists "settings admin write" on public.house_settings;
create policy "settings admin write" on public.house_settings
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- Semanas ajustadas: todos leen; solo el admin escribe.
drop policy if exists "overrides read" on public.week_overrides;
create policy "overrides read" on public.week_overrides
  for select to authenticated using ((select public.is_house_member()));

drop policy if exists "overrides admin write" on public.week_overrides;
create policy "overrides admin write" on public.week_overrides
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

-- Los clientes de inquilinos usarán operaciones que validen la asignación.
drop policy if exists "completions read" on public.task_completions;
create policy "completions read" on public.task_completions
  for select to authenticated using ((select public.is_house_member()));

drop policy if exists "completions insert own" on public.task_completions;
drop policy if exists "completions delete own" on public.task_completions;
drop policy if exists "completions admin write" on public.task_completions;
create policy "completions admin write" on public.task_completions
  for all to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

-- Los turnos requieren una operación atómica para cambiar el índice y registrar el historial.
drop policy if exists "trash read" on public.trash_state;
create policy "trash read" on public.trash_state
  for select to authenticated using ((select public.is_house_member()));

drop policy if exists "trash current update" on public.trash_state;
drop policy if exists "trash admin update" on public.trash_state;
create policy "trash admin update" on public.trash_state
  for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

drop policy if exists "trash logs read" on public.trash_logs;
create policy "trash logs read" on public.trash_logs
  for select to authenticated using ((select public.is_house_member()));

drop policy if exists "trash logs insert own" on public.trash_logs;
drop policy if exists "trash logs admin insert" on public.trash_logs;
create policy "trash logs admin insert" on public.trash_logs
  for insert to authenticated with check ((select public.is_admin()));

-- Pagos: todos leen; el admin edita cualquiera; cada uno edita el mes actual.
drop policy if exists "payments read" on public.payments;
create policy "payments read" on public.payments
  for select to authenticated using ((select public.is_house_member()));

drop policy if exists "payments write" on public.payments;
create policy "payments write" on public.payments
  for all to authenticated
  using (
    public.is_admin()
    or ((select public.is_house_member()) and user_id = auth.uid() and month = to_char(now() at time zone 'America/Bogota', 'YYYY-MM'))
  )
  with check (
    exists (select 1 from public.profiles where id = user_id and role = 'tenant')
    and (
      public.is_admin()
      or (
        user_id = auth.uid()
        and month = to_char(now() at time zone 'America/Bogota', 'YYYY-MM')
        and (marked_by is null or marked_by = auth.uid())
      )
    )
  );

-- Alertas leídas: cada uno solo ve y edita las suyas.
drop policy if exists "alerts read own" on public.alert_reads;
create policy "alerts read own" on public.alert_reads
  for select to authenticated using (user_id = auth.uid());

drop policy if exists "alerts write own" on public.alert_reads;
create policy "alerts write own" on public.alert_reads
  for all to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

-- ---------------------------------------------------------------------------
-- 7. Índices
-- ---------------------------------------------------------------------------
create index if not exists payments_month_idx on public.payments(month);
create index if not exists completions_week_idx on public.task_completions(week_start);
create index if not exists trash_logs_date_idx on public.trash_logs(emptied_at desc);
create index if not exists alert_reads_user_idx on public.alert_reads(user_id);
create index if not exists custom_tasks_week_idx on public.custom_tasks(week_start);
create index if not exists custom_turns_updated_idx on public.custom_turns(updated_at desc);

-- ---------------------------------------------------------------------------
-- 8. Realtime para sincronizar entre dispositivos
-- ---------------------------------------------------------------------------
do $$
declare
  table_name text;
begin
  foreach table_name in array array[
    'profiles',
    'week_overrides',
    'task_completions',
    'custom_tasks',
    'custom_turns',
    'trash_state',
    'payments'
  ]
  loop
    begin
      execute format(
        'alter publication supabase_realtime add table public.%I',
        table_name
      );
    exception when duplicate_object then
      null;
    end;
  end loop;
end;
$$;

commit;
